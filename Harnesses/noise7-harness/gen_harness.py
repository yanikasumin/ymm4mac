#!/usr/bin/env python3
"""Generate combos.swift for the NOISE7 harness from combos.CASES."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combos

ANIM_FIELDS = [
    "Strength", "Threshold", "Levels", "Octaves", "Lacunarity", "Gain",
    "WarpStrength", "WarpScale", "X", "Y", "Z", "Size",
    "ScaleX", "ScaleY", "ScaleZ", "Angle",
    "StripeInterval", "StripeWarpAmount", "FlowAmount",
]
FRACTAL_NAMES = ["Normal", "Turbulence", "Ridged"]
DISTANCE_NAMES = ["Euclidean", "Manhattan", "Chebyshev"]
OUTPUT_NAMES = {
    "Cellular": ["F1", "F2", "Difference"],
    "Voronoi": ["CellValue", "Edge"],
}

lines = []
lines.append("// Generated by gen_harness.py from combos.py — do not edit.")
lines.append("import YMM4Core")
lines.append("")
lines.append("struct NoiseCase {")
lines.append("    let name: String")
lines.append("    let type: NoiseType")
lines.append("    let typeName: String")
lines.append("    let isColor: Bool")
lines.append("    let fields: [(String, Double)]")
lines.append("    let fractalMode: String")
lines.append("    let distanceMode: String")
lines.append("    let outputMode: String")
lines.append("}")
lines.append("")
lines.append("let noiseCases: [NoiseCase] = [")

for c in combos.CASES:
    f = dict(c["fields"])
    field_strs = ", ".join(
        f'("{k}", {f[k]!r})' for k in ANIM_FIELDS)
    out_names = OUTPUT_NAMES.get(c["type"], ["F1"])
    out_name = out_names[min(int(f["OutputMode"]), len(out_names) - 1)]
    lines.append(
        f'    NoiseCase(name: "{c["name"]}", '
        f'type: .{c["type"].lower()}, typeName: "{c["type"]}", '
        f'isColor: {str(c["color"]).lower()}, '
        f'fields: [{field_strs}], '
        f'fractalMode: "{FRACTAL_NAMES[int(f["FractalMode"])]}", '
        f'distanceMode: "{DISTANCE_NAMES[int(f["DistanceMode"])]}", '
        f'outputMode: "{out_name}"),')

lines.append("]")
out_path = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "Sources", "harness", "combos.swift")
with open(out_path, "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("wrote", out_path)
