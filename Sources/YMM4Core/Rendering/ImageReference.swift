import Foundation

/// 描画グラフへの不透明な参照。本家 `ID2D1Image` の Mac 側の置換型。
///
/// 契約（技術仕様 第1章 IMG-01〜03・IMG-05 で確定、本実装はその保持のみ）:
/// - これはスナップショットではなく、描画グラフへの参照である。ピクセルの
///   実体は持たず、実体の生成・解放は将来の GPU 実行層の責務とする。
/// - 有効範囲は「生成した Update の直後から、次の Update が始まるまで」。
///   次回 Update で破棄・差し替えされうるため、Update をまたいで保持する
///   契約は存在しない。
/// - 参照の同一性と内容の同一性は別物である（動画のように、同じ参照でも
///   内容が変わりうる）。
/// - 入力として設定すること（SetInput 相当）は所有権を移さない。入力の
///   解除は、設定されていた入力を破棄しない。
public final class ImageReference {
    /// デバッグ用の識別ラベル。描画内容には影響しない。
    public let label: String

    public init(label: String = "") {
        self.label = label
    }
}
